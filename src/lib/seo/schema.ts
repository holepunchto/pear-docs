// Vendored from @tetherto/docs-seo-schema@1.1.0, extended with this site's frontmatter.
/**
 * SEO-related frontmatter fields for Fumadocs MDX collections. Imported by
 * `source.config.ts` (loaded by raw Node), so it must only depend on zod.
 */
import { z } from 'zod';

export const jsonLdSchemaTypeSchema = z.enum([
  'TechArticle',
  'APIReference',
  'WebPage',
]);

export const docTypeSchema = z.enum([
  'tutorial',
  'how-to',
  'reference',
  'explanation',
  'page',
  'faq',
  'getting-started',
]);

// Which product nav root(s) a page belongs to. Orthogonal to docType (which
// quadrant) — this is which sidebar.tabs tree(s) surface the page. 'shared'
// pages (e.g. troubleshooting) are listed in both trees. See
// docs/plans/PEAR-BARE-SPLIT-PITCH.md for the 2-product split this backs.
// 'p2p' added for the follow-up 3-product split: the building blocks
// (Hypercore, Hyperswarm, Autobase, ...) and their how-tos/Getting Started
// moved out of Bare into their own root — see git history for the pitch.
export const productSchema = z.enum(['pear', 'bare', 'p2p', 'shared']);

export const tetherSeoFrontmatterSchema = z.object({
  /** Non-empty after trim; required for meta, Open Graph / Twitter, and JSON-LD. */
  description: z
    .string()
    .trim()
    .min(1, 'description is required for SEO (meta, Open Graph, JSON-LD)'),
  // Optional SEO override for the <title> only (not the on-page <h1>, which
  // stays `title`). Descriptive part WITHOUT the brand suffix — the root
  // layout's title template appends " | Pear Docs". Use it to lengthen short,
  // single-word titles that Semrush flags as too short.
  seoTitle: z.string().trim().min(1).optional(),
  noIndex: z.boolean().optional(),
  ogImage: z.string().optional(),
  schemaType: jsonLdSchemaTypeSchema.optional(),
  docType: docTypeSchema.optional(),
  product: productSchema.optional(),
  lastModified: z.union([z.string(), z.coerce.date()]).optional(),
  // The upstream release this reference page was written and verified against.
  // Bare SemVer, no leading `v` (e.g. "11.34.0"); prereleases allowed.
  //
  // Reference pages track their own upstream module's version, NOT the Pear
  // platform version — hypercore's API doesn't change when Pear does. See
  // docs/plans/DOCS-VERSIONING-DESIGN.md §1.
  //
  // Two consumers:
  //   1. `npm run check:upstream-pins` grades drift against npm latest
  //      (patch = info, minor = warn, major = needs a new versioned page).
  //   2. The page template renders a "documented against" marker from it, so
  //      readers can tell whether the page matches their installed version.
  upstreamVersion: z
    .string()
    .trim()
    .regex(
      /^\d+\.\d+\.\d+(?:-[0-9A-Za-z-.]+)?$/,
      'upstreamVersion must be a bare SemVer without a leading "v" (e.g. "11.34.0")',
    )
    .optional(),
});

export type TetherSeoFrontmatter = z.infer<typeof tetherSeoFrontmatterSchema>;
export type JsonLdSchemaType = z.infer<typeof jsonLdSchemaTypeSchema>;
export type DocType = z.infer<typeof docTypeSchema>;

// --- Frontmatter gap warnings (console; deduped per page in-process).
//
// Two env knobs:
//   - DOCS_SEO_SILENT=1            silence ALL warnings (incl. required `description`).
//   - DOCS_SEO_QUIET_GENERATED=1   silence warnings for fields that have sensible
//                                  auto-generated/inferred defaults so they're noise
//                                  in pipelines that opt into them:
//                                    - `ogImage`      (auto-generated by Takumi prebuild)
//                                    - `schemaType`   (inferred from docType + URL path)
//                                    - `lastModified` (auto-injected by fumadocs-mdx
//                                                     `lastModified` plugin from git)
//                                  Warnings for `description` and `docType` stay loud
//                                  because neither has a useful default.

export const DOCS_SEO_WARN_PREFIX = '[@tetherto/docs-seo]';

const warnedSlugKeys = new Set<string>();

/**
 * Frontmatter fields whose missing-warning is silenced by DOCS_SEO_QUIET_GENERATED=1.
 * Exposed so callers (and tests) can reason about the same set the runtime uses.
 */
export const DOCS_SEO_GENERATED_FIELDS = [
  'ogImage',
  'schemaType',
  'lastModified',
] as const satisfies readonly (keyof TetherSeoFrontmatter)[];

function slugDedupeKey(slugs: string[]): string {
  return slugs.length === 0 ? '' : slugs.join('/');
}

function pageLabel(slugs: string[]): string {
  if (slugs.length === 0) return '/';
  return `/${slugs.join('/')}/`;
}

function seoWarningsSilent(): boolean {
  return process.env.DOCS_SEO_SILENT === '1';
}

function generatedFieldsQuiet(): boolean {
  return process.env.DOCS_SEO_QUIET_GENERATED === '1';
}

function missingDescription(data: Record<string, unknown>): boolean {
  const v = data.description;
  if (v === undefined || v === null) return true;
  if (typeof v === 'string') return v.trim().length === 0;
  return false;
}

function missingOptionalEnumish(data: Record<string, unknown>, key: string): boolean {
  return data[key] === undefined || data[key] === null;
}

function missingNonEmptyString(data: Record<string, unknown>, key: string): boolean {
  const v = data[key];
  if (v === undefined || v === null) return true;
  if (typeof v === 'string') return v.trim().length === 0;
  return false;
}

function missingLastModified(data: Record<string, unknown>): boolean {
  const v = data.lastModified;
  if (v === undefined || v === null) return true;
  if (v instanceof Date) return Number.isNaN(v.getTime());
  if (typeof v === 'string') return v.trim().length === 0;
  return false;
}

export type WarnMissingSeoFrontmatterOptions = {
  /** @default console.warn */
  warn?: (message: string) => void;
};

/**
 * Emits one console warning per missing SEO-related frontmatter field.
 * Dedupes by slug path so multiple packages can call this for the same page safely.
 *
 * Required `description` is enforced by `tetherSeoFrontmatterSchema` at MDX compile time;
 * this still warns if raw content (e.g. gray-matter) is missing it before validation.
 */
export function warnMissingSeoFrontmatterFields(
  data: Record<string, unknown>,
  slugs: string[],
  options?: WarnMissingSeoFrontmatterOptions,
): void {
  if (seoWarningsSilent()) return;

  const key = slugDedupeKey(slugs);
  if (warnedSlugKeys.has(key)) return;
  warnedSlugKeys.add(key);

  const warn = options?.warn ?? console.warn;
  const label = pageLabel(slugs);

  if (missingDescription(data)) {
    warn(
      `${DOCS_SEO_WARN_PREFIX} ${label} frontmatter "description" is missing or empty (required for meta, Open Graph, JSON-LD).`,
    );
  }

  const quietGenerated = generatedFieldsQuiet();

  if (!quietGenerated && missingNonEmptyString(data, 'ogImage')) {
    warn(
      `${DOCS_SEO_WARN_PREFIX} ${label} frontmatter "ogImage" is missing (using generated or default social image).`,
    );
  }

  if (!quietGenerated && missingOptionalEnumish(data, 'schemaType')) {
    warn(
      `${DOCS_SEO_WARN_PREFIX} ${label} frontmatter "schemaType" is missing (JSON-LD @type is inferred from path / docType).`,
    );
  }

  if (missingOptionalEnumish(data, 'docType')) {
    warn(
      `${DOCS_SEO_WARN_PREFIX} ${label} frontmatter "docType" is missing (set for clearer Diátaxis / JSON-LD defaults).`,
    );
  }

  if (!quietGenerated && missingLastModified(data)) {
    warn(
      `${DOCS_SEO_WARN_PREFIX} ${label} frontmatter "lastModified" is missing (sitemap lastmod / JSON-LD dates will be omitted).`,
    );
  }
}
